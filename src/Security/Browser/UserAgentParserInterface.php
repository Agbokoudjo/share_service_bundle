namespace Wlindabla\ShareServiceBundle\Security\Browser;

/**
 * Contract for extracting a human-readable browser/OS label from a raw
 * HTTP User-Agent string.
 *
 * @author AGBOKOUDJO Franck <internationaleswebservices@gmail.com>
 * @package <https://github.com/Agbokoudjo/>
 */
interface UserAgentParserInterface
{
    /**
     * Returns a readable label such as "Chrome 128 on Windows 10", or null
     * when the given string is empty/absent.
     */
    public function parse(?string $rawUserAgent): ?string;
}
